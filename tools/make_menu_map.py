#!/usr/bin/env python3
"""Generate addon/menu-map.js from an arrangement file.

The add-on runs inside the client's sandbox and cannot read files outside its
own package, so the folder-to-heading arrangement has to travel with it. This
script turns your own arrangement into that file.

The arrangement file is JSON:

    {
      "headings": ["Urgent", "Professional", "Administrative", "Personal", "Agentic"],
      "map": {
        "matters - active": "Professional",
        "financial / BAS": "Administrative"
      }
    }

Usage:
    python3 tools/make_menu_map.py arrangement.json addon/menu-map.js

Only the headings and the arrangement are copied; nothing else from your
machine is written into the add-on.
"""
import argparse
import json
import sys


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", help="arrangement file (JSON)")
    parser.add_argument("output", nargs="?", default="addon/menu-map.js",
                        help="file to write (default: addon/menu-map.js)")
    args = parser.parse_args()

    with open(args.source, encoding="utf-8") as fh:
        cfg = json.load(fh)

    headings = cfg.get("headings") or []
    mapping = cfg.get("map") or {}
    if not headings or not mapping:
        print("the arrangement needs both 'headings' and 'map'", file=sys.stderr)
        return 2

    unknown = sorted({h for h in mapping.values() if h not in headings})
    if unknown:
        print("warning: headings in the map but not in 'headings': "
              + ", ".join(unknown), file=sys.stderr)

    lines = [
        "/* This Source Code Form is subject to the terms of the Mozilla Public",
        " * License, v. 2.0. If a copy of the MPL was not distributed with this",
        " * file, You can obtain one at https://mozilla.org/MPL/2.0/. */",
        "",
        "/* Generated by tools/make_menu_map.py. */",
        "",
        "const TRENCHER_MENU = {",
        "  headings: " + json.dumps(headings, ensure_ascii=False) + ",",
        "  map: {",
    ]
    items = sorted(mapping.items(), key=lambda kv: kv[0].lower())
    for i, (path, heading) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f"    {json.dumps(path, ensure_ascii=False)}: "
                     f"{json.dumps(heading, ensure_ascii=False)}{comma}")
    lines += ["  }", "};", ""]

    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {args.output}: {len(items)} folders under {len(headings)} headings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
